#!/usr/bin/env python3
"""Regenerate desktop/docs/spec/settings-wiring.ru.md from ui/settings/wiring.py and the schema."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from seohead_desktop.i18n import set_language, tr  # noqa: E402
from seohead_desktop.ui.settings import full_schema, wiring  # noqa: E402

HEAD = """# Settings: applied capabilities and stored preferences

Generated by `python scripts/gen_settings_wiring.py` from `ui/settings/wiring.py`.
Every schema key must be classified. Stored-only settings show an explicit unavailable badge;
saving a preference does not imply that the corresponding capability is implemented.
The historical filename is retained for compatibility with the settings documentation contract.

| Key | Current behavior | Implementation step | Dependency |
|---|---|---|---|
"""


def render():
    set_language("en")
    lines = [HEAD.rstrip("\n")]
    for key, step, reason in wiring.table(full_schema()):
        lines.append(
            f"| `{key}` | {'Applied' if step is None else 'Stored only'} | {step or '—'} | {(tr(reason) + (f' (#{wiring.ISSUES[key]})' if key in wiring.ISSUES else '')) if reason else '—'} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    target = ROOT / "docs/spec/settings-wiring.ru.md"
    target.write_text(render(), encoding="utf-8")
    print(target)
