//! Text-driven selector suggestions for extraction rules.
//!
//! Given one sample document and the visible text of the element a user would
//! otherwise click in a visual builder, locate the matching element(s) and
//! propose candidate selectors in stability order — ids and semantic
//! attributes first, then the shortest class-signature path anchored at a
//! stable ancestor, then a positional `nth-of-type` fallback only when no
//! unique candidate exists. Every candidate's match count is measured against
//! the whole document with the same closed selector engine extraction rules
//! run under, so an emitted rule evaluates identically in `scan-extract`
//! without modification.

use std::collections::{HashMap, HashSet};
use std::sync::LazyLock;

use serde_json::{json, Map, Value};
use spiderhead_parse::dom::{self, ElementRef, Selector};
use spiderhead_parse::extraction_rules::{validate_rules, MAX_MATCHES};

/// Version marker carried by every result document.
pub const VERSION: &str = "extraction_suggest.v1";
const MAX_HTML_BYTES: usize = 8 * 1024 * 1024;
const MAX_TEXT_LENGTH: usize = 2048;
const MAX_TARGETS: usize = 5;
const MAX_CANDIDATES: usize = 12;
const MAX_SAMPLES: usize = 3;
const MAX_SAMPLE_CHARS: usize = 200;
const MAX_PATH_DEPTH: usize = 4;
const MAX_SELECTOR_CHARS: usize = 512;
/// Elements whose text is code or placeholder, never rendered page copy.
const SKIP_TAGS: [&str; 4] = ["script", "style", "template", "noscript"];
fn re(pattern: &'static str) -> regex::Regex {
    regex::Regex::new(pattern).unwrap_or_else(|_| unreachable!("static pattern {pattern}"))
}

/// Attribute values worth anchoring on: identifier-shaped, human-chosen.
static VALUE_OK: LazyLock<regex::Regex> = LazyLock::new(|| re(r"\A[A-Za-z][A-Za-z0-9_-]{0,63}\z"));
/// Digit runs of four or more read as generated, not human-chosen.
static AUTOGENERATED: LazyLock<regex::Regex> = LazyLock::new(|| re(r"\d{4,}"));
/// A bare `#id` selector: the element's own id, not an id-anchored chain.
static BARE_ID: LazyLock<regex::Regex> = LazyLock::new(|| re(r"\A#[A-Za-z0-9_:-]+\z"));

fn strategy_rank(strategy: &str) -> u8 {
    match strategy {
        "id" => 0,
        "semantic" => 1,
        "path" => 2,
        _ => 3,
    }
}

/// Normalize an element's text exactly like extraction rules do.
fn norm(el: &ElementRef<'_>) -> String {
    collapse(&dom::get_text(el, " "))
}

fn collapse(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// CSS identifier escape matching the oracle's selector engine: unchanged for
/// identifier characters, `\c` for punctuation, `\{hex} ` for control bytes
/// and leading digits.
fn css_escape(ident: &str) -> String {
    let chars: Vec<char> = ident.chars().collect();
    if chars.len() == 1 && chars[0] == '-' {
        return format!("\\{}", ident);
    }
    let leading_dash = chars.first() == Some(&'-');
    let mut out = String::with_capacity(ident.len());
    for (index, c) in chars.iter().enumerate() {
        let codepoint = *c as u32;
        if codepoint == 0 {
            out.push('\u{FFFD}');
        } else if (0x01..=0x1F).contains(&codepoint)
            || codepoint == 0x7F
            || ((index == 0 || (leading_dash && index == 1)) && (0x30..=0x39).contains(&codepoint))
        {
            out.push_str(&format!("\\{codepoint:x} "));
        } else if codepoint == 0x2D
            || codepoint == 0x5F
            || codepoint >= 0x80
            || (0x30..=0x39).contains(&codepoint)
            || (0x41..=0x5A).contains(&codepoint)
            || (0x61..=0x7A).contains(&codepoint)
        {
            out.push(*c);
        } else {
            out.push('\\');
            out.push(*c);
        }
    }
    out
}

/// One class-signature path step: `tag.class1.class2`.
fn step(el: &ElementRef<'_>) -> String {
    let mut out = el.value().name().to_owned();
    if let Some(classes) = dom::attr(el, "class") {
        for name in classes.split_whitespace() {
            out.push('.');
            out.push_str(&css_escape(name));
        }
    }
    out
}

/// One positional path step: `tag:nth-of-type(index)` (1-based).
fn nth_step(el: &ElementRef<'_>) -> String {
    let name = el.value().name();
    let mut same = 0usize;
    let mut node = el.prev_sibling();
    while let Some(current) = node {
        if let Some(sibling) = ElementRef::wrap(current) {
            if sibling.value().name() == name {
                same += 1;
            }
        }
        node = current.prev_sibling();
    }
    format!("{name}:nth-of-type({})", same + 1)
}

/// Root-first element chain from the document root down to `target`.
fn chain<'a>(target: &ElementRef<'a>) -> Vec<ElementRef<'a>> {
    let mut chain: Vec<ElementRef<'a>> = vec![*target];
    for node in target.ancestors() {
        if let Some(el) = ElementRef::wrap(node) {
            chain.push(el);
        }
    }
    chain.reverse();
    chain
}

/// Innermost elements whose normalized text equals `wanted`.
///
/// A wrapper whose whole text equals the same string (the card link around a
/// product title, or `body` itself on a tiny page) is not a separate target:
/// only elements that contain no other match are proposed.
fn visible_targets<'a>(soup: &'a dom::Soup, wanted: &str) -> Vec<ElementRef<'a>> {
    let hits: Vec<ElementRef<'a>> = dom::all_elements(soup)
        .filter(|el| {
            !SKIP_TAGS.contains(&el.value().name())
                && !el
                    .ancestors()
                    .filter_map(ElementRef::wrap)
                    .any(|a| SKIP_TAGS.contains(&a.value().name()))
                && norm(el) == wanted
        })
        .collect();
    let mut ancestors: HashSet<ego_tree::NodeId> = HashSet::new();
    for hit in &hits {
        ancestors.extend(hit.ancestors().map(|node| node.id()));
    }
    hits.into_iter()
        .filter(|el| !ancestors.contains(&el.id()))
        .collect()
}

/// Attribute selectors over stable, human-chosen attribute values.
fn semantic_selectors(target: &ElementRef<'_>) -> Vec<String> {
    let name = target.value().name();
    let mut attrs: Vec<(&str, &str)> = Vec::new();
    if let Some(value) = dom::attr(target, "itemprop") {
        attrs.push(("itemprop", value));
    }
    let mut data: Vec<(&str, &str)> = target
        .value()
        .attrs()
        .filter(|(key, _)| key.starts_with("data-"))
        .collect();
    data.sort_by(|a, b| a.0.cmp(b.0));
    attrs.extend(data);
    if let Some(value) = dom::attr(target, "name") {
        attrs.push(("name", value));
    }
    let mut selectors: Vec<String> = Vec::new();
    for (attr, value) in attrs {
        if !VALUE_OK.is_match(value) || AUTOGENERATED.is_match(value) {
            continue;
        }
        selectors.push(format!("{name}[{attr}=\"{}\"]", css_escape(value)));
        if selectors.len() == 3 {
            break;
        }
    }
    selectors
}

/// One proposed selector with its measured document-wide match count.
struct Candidate {
    selector: String,
    strategy: &'static str,
    matches: usize,
    sample_matches: Vec<String>,
}

/// Measure every proposed selector and drop dead ones.
fn verify(soup: &dom::Soup, found: &[(&'static str, String)]) -> Vec<Candidate> {
    let mut out: Vec<Candidate> = Vec::new();
    let mut seen: HashSet<&str> = HashSet::new();
    for (strategy, selector) in found {
        if selector.len() > MAX_SELECTOR_CHARS || !seen.insert(selector.as_str()) {
            continue;
        }
        let Ok(parsed) = Selector::parse(selector) else {
            continue;
        };
        let elements: Vec<ElementRef<'_>> = dom::all_elements(soup)
            .filter(|el| parsed.matches(el))
            .collect();
        out.push(Candidate {
            selector: selector.clone(),
            strategy,
            matches: elements.len(),
            sample_matches: elements
                .iter()
                .take(MAX_SAMPLES)
                .map(|el| norm(el).chars().take(MAX_SAMPLE_CHARS).collect())
                .collect(),
        });
    }
    out
}

/// Match count of a generation-only selector; these are engine-valid by
/// construction, so an unreachable parse error counts as no match.
fn count_matches(soup: &dom::Soup, selector: &str) -> usize {
    match Selector::parse(selector) {
        Ok(parsed) => dom::all_elements(soup)
            .filter(|el| parsed.matches(el))
            .count(),
        Err(_) => 0,
    }
}

/// Candidate selectors for one target, in generation order (stability ladder).
fn candidates_for(soup: &dom::Soup, target: &ElementRef<'_>) -> Vec<Candidate> {
    let chain = chain(target);
    let max_depth = MAX_PATH_DEPTH.min(chain.len().saturating_sub(1));
    let mut found: Vec<(&'static str, String)> = Vec::new();
    if let Some(own_id) = dom::attr(target, "id").filter(|id| !id.is_empty()) {
        found.push(("id", format!("#{}", css_escape(own_id))));
    }
    for depth in 1..=max_depth {
        let ancestor = &chain[chain.len() - 1 - depth];
        if let Some(anchor) = dom::attr(ancestor, "id").filter(|id| !id.is_empty()) {
            let steps = chain[chain.len() - depth..]
                .iter()
                .map(step)
                .collect::<Vec<_>>()
                .join(" ");
            found.push(("id", format!("#{} {}", css_escape(anchor), steps)));
            break;
        }
    }
    found.extend(
        semantic_selectors(target)
            .into_iter()
            .map(|selector| ("semantic", selector)),
    );
    let signature = step(target);
    found.push(("path", signature.clone()));
    if count_matches(soup, &signature) != 1 {
        for depth in 1..=max_depth {
            let selector = chain[chain.len() - 1 - depth..]
                .iter()
                .map(step)
                .collect::<Vec<_>>()
                .join(" ");
            if count_matches(soup, &selector) == 1 {
                found.push(("path", selector));
                break;
            }
        }
    }
    let mut verified = verify(soup, &found);
    if !verified.iter().any(|candidate| candidate.matches == 1) {
        for depth in 1..=max_depth {
            let selector = chain[chain.len() - 1 - depth..]
                .iter()
                .map(nth_step)
                .collect::<Vec<_>>()
                .join(" > ");
            if count_matches(soup, &selector) == 1 {
                verified.extend(verify(soup, &[("nth", selector)]));
                break;
            }
        }
    }
    verified
}

/// A rule id derived from the target text; `element` when nothing survives.
fn slug(text: &str) -> String {
    let lowered = text.to_lowercase();
    let mut substituted = String::with_capacity(lowered.len());
    let mut in_run = false;
    for c in lowered.chars() {
        if c.is_ascii_lowercase() || c.is_ascii_digit() {
            substituted.push(c);
            in_run = false;
        } else if !in_run {
            substituted.push('-');
            in_run = true;
        }
    }
    let trimmed = substituted.trim_matches('-');
    let sliced: String = trimmed.chars().take(48).collect();
    let slug = sliced.trim_matches('-');
    if slug.is_empty() {
        return "element".to_owned();
    }
    let first = slug.chars().next().unwrap_or('a');
    if !first.is_ascii_alphabetic() {
        return format!("element-{}", slug).chars().take(48).collect();
    }
    slug.to_owned()
}

/// Build the validated extraction-rule document for one candidate.
fn emit_rule_for(
    candidate: &Candidate,
    text: &str,
    rule_id: Option<&str>,
) -> Result<Value, String> {
    let max_matches = (candidate.matches.max(1) as u32).min(MAX_MATCHES);
    let rule = json!({
        "id": rule_id.map(str::to_owned).unwrap_or_else(|| slug(text)),
        "kind": "text",
        "selector": candidate.selector,
        "operator": "equals",
        "value": text,
        "max_matches": max_matches,
    });
    // The oracle validates the rule as a one-element rule list, not bare.
    validate_rules(&json!([rule.clone()])).map_err(|error| error.to_string())?;
    Ok(rule)
}

/// Suggest extraction-rule selectors for the element holding `text`.
///
/// Pure and offline: one parsed document in, candidates with measured
/// document-wide match counts out. `emit_rule` attaches a ready
/// extraction-rule document for the best candidate, validated with the same
/// closed grammar `scan-extract` applies, so it runs there unchanged.
pub fn suggest(
    html: &str,
    text: &str,
    emit_rule: bool,
    rule_id: Option<&str>,
) -> Result<Value, String> {
    if html.trim().is_empty() {
        return Err("html must be a non-empty document string".to_owned());
    }
    if text.trim().is_empty() {
        return Err("text must be the non-empty visible text of the element".to_owned());
    }
    let wanted = collapse(text);
    if wanted.chars().count() > MAX_TEXT_LENGTH {
        return Err(format!(
            "target text exceeds the {MAX_TEXT_LENGTH}-character extraction rule value limit"
        ));
    }
    if html.len() > MAX_HTML_BYTES {
        return Err("document exceeds the 8 MiB extraction suggest budget".to_owned());
    }
    let soup = dom::parse_document(html);
    let targets = visible_targets(&soup, &wanted);
    let mut collected: HashMap<String, Candidate> = HashMap::new();
    for target in &targets {
        for candidate in candidates_for(&soup, target) {
            collected
                .entry(candidate.selector.clone())
                .or_insert(candidate);
        }
    }
    let mut ordered: Vec<Candidate> = collected.into_values().collect();
    ordered.sort_by(|a, b| {
        strategy_rank(a.strategy)
            .cmp(&strategy_rank(b.strategy))
            .then_with(|| {
                usize::from(!BARE_ID.is_match(&a.selector))
                    .cmp(&usize::from(!BARE_ID.is_match(&b.selector)))
            })
            .then_with(|| a.selector.len().cmp(&b.selector.len()))
            .then_with(|| a.selector.cmp(&b.selector))
    });
    ordered.truncate(MAX_CANDIDATES);

    let candidates: Vec<Value> = ordered
        .iter()
        .enumerate()
        .map(|(index, candidate)| {
            let mut object = Map::new();
            object.insert("selector".into(), json!(candidate.selector));
            object.insert("strategy".into(), json!(candidate.strategy));
            object.insert("matches".into(), json!(candidate.matches));
            object.insert("sample_matches".into(), json!(candidate.sample_matches));
            if index == 0 {
                object.insert("best".into(), json!(true));
            }
            Value::Object(object)
        })
        .collect();

    let mut result = Map::new();
    result.insert("ok".into(), json!(true));
    result.insert("format".into(), json!(VERSION));
    result.insert("text".into(), json!(wanted));
    result.insert("elements_matched".into(), json!(targets.len()));
    result.insert(
        "targets_considered".into(),
        json!(targets.len().min(MAX_TARGETS)),
    );
    result.insert("candidates".into(), Value::Array(candidates));
    if ordered.is_empty() {
        result.insert(
            "note".into(),
            json!("no element with the requested text was found in the document"),
        );
    } else if targets.len() > MAX_TARGETS {
        result.insert(
            "note".into(),
            json!(format!(
                "{} elements match the text; only the innermost {} produced candidates",
                targets.len(),
                MAX_TARGETS
            )),
        );
    }
    if emit_rule {
        let best = ordered
            .first()
            .ok_or_else(|| "cannot emit a rule: no candidate selectors were found".to_owned())?;
        let rule = emit_rule_for(best, &wanted, rule_id)?;
        result.insert("rule".into(), rule);
    }
    Ok(Value::Object(result))
}
