//! Render the coverage document from the issue catalogue.
//!
//! so a committed document and the drift test read the same code path.

use spiderhead_formats::issue_map::{categories, coverage_counts, Status};

fn status_label(status: Status) -> &'static str {
    match status {
        Status::Check => "check",
        Status::Tool => "tool",
        Status::Partial => "partial",
        Status::Gap => "gap",
        Status::OutOfScope => "out of scope",
    }
}

fn refs(refs: &[&str]) -> String {
    if refs.is_empty() {
        "—".to_owned()
    } else {
        refs.iter()
            .map(|r| format!("`{r}`"))
            .collect::<Vec<_>>()
            .join(" ")
    }
}

fn header() -> Vec<String> {
    let counts = coverage_counts();
    let total = counts.total();
    let covered = counts.check + counts.tool;
    vec![
        "# Coverage against the published issue catalogue".to_owned(),
        String::new(),
        "*Generated by `scripts/generate_sf_coverage.py` from `spiderhead/sf/core/sf_issue_map.py`.".to_owned(),
        "Do not edit by hand.*".to_owned(),
        String::new(),
        "SpiderHead is agent-native: 254 MCP tools, citability scoring, AI-bot visibility,".to_owned(),
        "llms.txt checks — the AI surface is not a feature beside the crawler, it is how the".to_owned(),
        "product is driven. This table measures the *crawl-findings* catalogue only.".to_owned(),
        String::new(),
        "Screaming Frog publishes a list of the issues its crawler reports — the closest thing".to_owned(),
        "technical SEO has to a shared checklist. This measures us against it, because a count".to_owned(),
        "of our own checks is a number with nothing to compare to.".to_owned(),
        String::new(),
        "**Only the issue names are used.** They are the field's shared vocabulary for these".to_owned(),
        "problems, and naming a problem is not copying a description of it. Every explanation".to_owned(),
        "here is written about *our own* behaviour.".to_owned(),
        String::new(),
        "## Where we stand".to_owned(),
        String::new(),
        "| Status | Count | Meaning |".to_owned(),
        "|---|---:|---|".to_owned(),
        format!("| check | {} | a registry check finds it |", counts.check),
        format!(
            "| tool | {} | a command outside the crawl registry finds it |",
            counts.tool
        ),
        format!(
            "| partial | {} | we find part of it; the missing part is stated |",
            counts.partial
        ),
        format!("| gap | {} | we should find it and do not |", counts.gap),
        format!(
            "| out of scope | {} | a decision, with its reason |",
            counts.out_of_scope
        ),
        format!("| **total** | **{total}** | |"),
        String::new(),
        "Accessibility and AMP include measured subsets; their remaining limits are stated".to_owned(),
        "per issue below. Across the catalogue,".to_owned(),
        format!(
            "**{covered} issues are found today**, {} are",
            counts.partial
        ),
        format!(
            "found in part, {} are gaps worth closing, and",
            counts.gap
        ),
        format!(
            "{} need something we have decided not to build.",
            counts.out_of_scope
        ),
        String::new(),
        "A gap is not a defect. It is a named, deliberate absence — which is the only kind worth".to_owned(),
        "having, because the alternative is an absence nobody has noticed.".to_owned(),
        String::new(),
    ]
}

/// `render()`: the full coverage document as Markdown.
pub fn render() -> String {
    let mut lines = header();
    for category in categories() {
        lines.push(format!("## {}", category.name));
        lines.push(String::new());
        lines.push("| Issue | Status | Found by | Note |".to_owned());
        lines.push("|---|---|---|---|".to_owned());
        for entry in &category.entries {
            let note = entry.note.replace('|', "\\|");
            lines.push(format!(
                "| {} | {} | {} | {} |",
                entry.name,
                status_label(entry.status),
                refs(entry.refs),
                note
            ));
        }
        lines.push(String::new());
    }
    let mut out = lines.join("\n");
    while out.ends_with('\n') {
        out.pop();
    }
    out.push('\n');
    out
}
