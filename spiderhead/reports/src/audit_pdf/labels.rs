pub(super) static LABELS_EN: LazyLock<LabelTable> =
    LazyLock::new(|| EN_LABELS.iter().copied().collect());
pub(super) static LABELS_RU: LazyLock<LabelTable> =
    LazyLock::new(|| RU_LABELS.iter().copied().collect());

pub(super) fn labels(lang: &str) -> &'static LabelTable {
    if lang == "ru" {
        &LABELS_RU
    } else {
        &LABELS_EN
    }
}

pub(super) fn l(lang: &str, key: &str) -> &'static str {
    labels(lang).get(key).copied().unwrap_or("")
}
