/// Message for a transport failure: `"timeout"` gives `timed out`; any other kind gives
/// `<urlopen error kind>`.
pub fn url_error(kind: &str) -> String {
    if kind == "timeout" {
        "timed out".to_owned()
    } else {
        format!("<urlopen error {kind}>")
    }
}
